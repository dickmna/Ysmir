	consteval bool IsValidCalibrationCurve(const std::array<CurvePoint, N>& a_curve)
	{
		if constexpr (N == 0) {
			return false;
		}

		for (std::size_t i = 0; i < N; ++i) {
			if (a_curve[i].distance < 0.0f || a_curve[i].halfWidth <= 0.0f) {
				return false;
			}
			if (i > 0 && a_curve[i].distance <= a_curve[i - 1].distance) {
				return false;
			}
		}
		return true;
	}

